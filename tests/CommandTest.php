<?php

namespace RobTesch\InertiaFormGenerator\Tests;

use Illuminate\Support\Facades\Config;
use Illuminate\Support\Facades\File;

beforeEach(function () {
    $this->outDir = sys_get_temp_dir().'/inertia-form-generator-'.uniqid();
    Config::set('inertia-form-generator.output-file-path', $this->outDir.'/generated/forms.ts');
    Config::set('inertia-form-generator.additional_paths', [__DIR__.'/Fixtures/Requests']);
    Config::set('inertia-form-generator.user-model', null);
});

afterEach(function () {
    File::deleteDirectory($this->outDir);
});

it('writes a typed form factory for every discoverable request', function () {
    $this->artisan('inertia-form-generator:generate')
        ->expectsOutputToContain('Skipped RobTesch\InertiaFormGenerator\Tests\Fixtures\Requests\RouteDependentRequest')
        ->assertSuccessful();

    $contents = file_get_contents($this->outDir.'/generated/forms.ts');

    $prefix = 'RobTeschInertiaFormGeneratorTestsFixturesRequests';

    expect($contents)->toBe(<<<TS
        // This file is auto-generated by the inertia-form-generator package

        import { useForm } from '@inertiajs/vue3';

        export type {$prefix}NestedInjectedRequestFormData = {
          name: string;
        };

        export function use{$prefix}NestedInjectedRequestForm(overrides: Partial<{$prefix}NestedInjectedRequestFormData> = {}) {
          const defaults: {$prefix}NestedInjectedRequestFormData = {
            name: '',
          };

          return useForm<{$prefix}NestedInjectedRequestFormData>({ ...defaults, ...overrides });
        }

        export type {$prefix}StorePostRequestFormData = {
          title: string;
        };

        export function use{$prefix}StorePostRequestForm(overrides: Partial<{$prefix}StorePostRequestFormData> = {}) {
          const defaults: {$prefix}StorePostRequestFormData = {
            title: '',
          };

          return useForm<{$prefix}StorePostRequestFormData>({ ...defaults, ...overrides });
        }

        export type {$prefix}SupportedRequestFormData = {
          label: string;
        };

        export function use{$prefix}SupportedRequestForm(overrides: Partial<{$prefix}SupportedRequestFormData> = {}) {
          const defaults: {$prefix}SupportedRequestFormData = {
            label: '',
          };

          return useForm<{$prefix}SupportedRequestFormData>({ ...defaults, ...overrides });
        }

        TS);
});

it('never executes non-class files or instantiates abstract requests', function () {
    $this->artisan('inertia-form-generator:generate')->assertSuccessful();

    expect($GLOBALS['inertia_form_generator_helpers_loaded'] ?? false)->toBeFalse();
    expect(file_get_contents($this->outDir.'/generated/forms.ts'))->not->toContain('BaseRequest');
});

it('skips excluded requests', function () {
    Config::set('inertia-form-generator.exclude', [
        '\RobTesch\InertiaFormGenerator\Tests\Fixtures\Requests\StorePostRequest',
    ]);

    $this->artisan('inertia-form-generator:generate')->assertSuccessful();

    expect(file_get_contents($this->outDir.'/generated/forms.ts'))->not->toContain('StorePostRequest');
});

it('fails without touching the existing file when every request is skipped', function () {
    Config::set('inertia-form-generator.exclude', [
        'RobTesch\InertiaFormGenerator\Tests\Fixtures\Requests\StorePostRequest',
        'RobTesch\InertiaFormGenerator\Tests\Fixtures\Requests\SupportedRequest',
        'RobTesch\InertiaFormGenerator\Tests\Fixtures\Requests\Nested\InjectedRequest',
    ]);
    File::ensureDirectoryExists($this->outDir.'/generated');
    File::put($this->outDir.'/generated/forms.ts', 'existing');

    $this->artisan('inertia-form-generator:generate')
        ->expectsOutputToContain('No forms were generated')
        ->assertFailed();

    expect(file_get_contents($this->outDir.'/generated/forms.ts'))->toBe('existing');
});
