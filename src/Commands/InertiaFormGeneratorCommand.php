<?php

namespace RobTesch\InertiaFormGenerator\Commands;

use Illuminate\Console\Command;
use Illuminate\Support\Facades\Config;
use Illuminate\Support\Facades\File;
use RobTesch\InertiaFormGenerator\InertiaFormGenerator;

class InertiaFormGeneratorCommand extends Command
{
    public $signature = 'inertia-form-generator:generate';

    public $description = 'Generate Inertia form requests from your Laravel FormRequests';

    public function handle(InertiaFormGenerator $generator): int
    {
        $import = $generator->getUseFormImportForProvider(
            Config::get('inertia-form-generator.front-end-provider', 'vue'),
        );

        $transformed = $generator->transformRequests($generator->getFormRequests());

        foreach ($generator->warnings() as $warning) {
            $this->warn($warning);
        }

        if ($transformed === [] && $generator->warnings() !== []) {
            $this->error('No forms were generated, so the existing file was left untouched.');

            return self::FAILURE;
        }

        $outFile = $generator->absolutePath(Config::get('inertia-form-generator.output-file-path', 'resources/js/formRequests.ts'));

        File::ensureDirectoryExists(dirname($outFile));

        if (File::put($outFile, $this->render($import, $transformed)) === false) {
            $this->error('Unable to write '.$outFile);

            return self::FAILURE;
        }

        $this->info('File exported to '.$outFile);

        return self::SUCCESS;
    }

    /**
     * @param  list<array{name: string, type: string, initial: string}>  $transformed
     */
    private function render(string $import, array $transformed): string
    {
        $contents = '// This file is auto-generated by the inertia-form-generator package'.PHP_EOL;

        if ($transformed === []) {
            return $contents;
        }

        $contents .= PHP_EOL.$import.PHP_EOL;

        foreach ($transformed as $form) {
            $type = $form['name'].'FormData';
            $initial = str_replace(PHP_EOL, PHP_EOL.'  ', $form['initial']);

            $contents .= PHP_EOL.'export type '.$type.' = '.$form['type'].';'.PHP_EOL.PHP_EOL;
            $contents .= 'export function use'.$form['name'].'Form(overrides: Partial<'.$type.'> = {}) {'.PHP_EOL;
            $contents .= '  const defaults: '.$type.' = '.$initial.';'.PHP_EOL.PHP_EOL;
            $contents .= '  return useForm<'.$type.'>({ ...defaults, ...overrides });'.PHP_EOL;
            $contents .= '}'.PHP_EOL;
        }

        return $contents;
    }
}
